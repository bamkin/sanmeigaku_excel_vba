def kanshi(n: int) -> str:
    """六十干支番号（1〜60）→ 干支。"""
    n = (n - 1) % 60
    return STEMS[n % 10] + BRANCHES[n % 12]


def kanshi_number(stem: str, branch: str) -> int:
    """干支 → 番号（1〜60）。"""
    s, b = STEMS.index(stem), BRANCHES.index(branch)
    for n in range(60):
        if n % 10 == s and n % 12 == b:
            return n + 1
    raise ValueError(f"無効な干支: {stem}{branch}")


def kanshi_to_number(ks: str) -> int:
    return kanshi_number(ks[0], ks[1])


